def mix(hex_col, a):
    """hex_col blended with white, a = 0 -> white, 1 -> hex_col."""
    c = np.array([int(hex_col[i:i + 2], 16) for i in (1, 3, 5)])
    c = np.round(255 - a * (255 - c)).astype(int)
    return "#%02x%02x%02x" % tuple(c)


# ------------------------------------------------------------------ data: real clip through the pre-trained VAE
def real_clip(j, vae_path):
    q = load("testing")
    x = q["x"][j, :q["lengths"][j]]
    model, _ = vae_mod.load(vae_path)
    mu, logvar = jax.vmap(model.encode)(jnp.asarray(x))
    rec = jax.vmap(model.decode)(mu)
    return x, np.asarray(mu), np.asarray(rec)


# ------------------------------------------------------------------ data: synthetic MTGP (schematic)
def kmat(kernel, a, b):
    return np.asarray(kernel(jnp.asarray(a[:, None]), jnp.asarray(b[:, None])), np.float64)


def synthetic(n_r, seed=3):
    rng = np.random.default_rng(seed)
    k0 = kernax.VarianceKernel(0.6) * kernax.Matern52Kernel(length_scale=0.18)
    ks = kernax.VarianceKernel(0.08) * kernax.Matern52Kernel(length_scale=0.35)

    def mu_true(t):
        return 0.15 + 1.1 * np.exp(-((t - 0.38) / 0.14) ** 2) - 0.75 * np.exp(-((t - 0.78) / 0.12) ** 2)

    clips = []  # (t, y, sd), clip r first
    lengths = [n_r] + list(rng.integers(10, 22, size=11))
    for i, n in enumerate(lengths):
        t = np.arange(n) / (n - 1)
        e = rng.multivariate_normal(np.zeros(n), kmat(ks, t, t) + 1e-9 * np.eye(n))
        if i == 0:  # clip r: a visible deviation (later and higher at the end)
            e = 0.35 * np.exp(-((t - 0.85) / 0.15) ** 2) - 0.12 + 0.3 * e
        sd = rng.uniform(0.04, 0.13, n)
        y = mu_true(t) + e + sd * rng.standard_normal(n)
        clips.append((t, y, sd))

    # exact joint posterior of mu_s and e_r on a grid, given every clip (noise = encoder variance)
    g = np.linspace(0, 1, 200)
    T = np.concatenate([c[0] for c in clips])
    Y = np.concatenate([c[1] for c in clips])
    R = np.concatenate([np.full(len(c[0]), i) for i, c in enumerate(clips)])
    same = R[:, None] == R[None, :]
    C = kmat(k0, T, T) + same * kmat(ks, T, T) + np.diag(np.concatenate([c[2] for c in clips]) ** 2)
    L = np.linalg.cholesky(C + 1e-9 * np.eye(len(T)))

    def post(Kgy, Kgg):
        A = np.linalg.solve(L, Kgy.T)
        m = A.T @ np.linalg.solve(L, Y)
        v = np.diag(Kgg) - (A ** 2).sum(0)
        return m, np.sqrt(np.maximum(v, 0))

    k0_gy, ks_gy = kmat(k0, g, T), kmat(ks, g, T) * (R == 0)[None, :]
    mu = post(k0_gy, kmat(k0, g, g))
    e = post(ks_gy, kmat(ks, g, g))
    z = post(k0_gy + ks_gy, kmat(k0, g, g) + kmat(ks, g, g))
    return clips, g, mu, e, z


# ------------------------------------------------------------------ stacks (frames drawn back to front, as in a film strip)
OFF = np.array([9.0, -8.0])  # shift of each earlier frame (up-right): the stack depth is time


def stack(svg, n, cx, cy, draw):
    """draw(svg, x_centre, y_centre, k, opacity) for k = n-1 (back) ... 0 (front)."""
    for k in range(n - 1, -1, -1):
        c = np.array([cx, cy]) + (k - (n - 1) / 2) * OFF
        draw(svg, c[0], c[1], k, 1.0 if k == 0 else 0.35)


def skeleton_card(frames, box_h, pad=5):
    pts = np.concatenate([f.reshape(-1, 2) for f in frames])
    lo, hi = pts.min(0), pts.max(0)
    scale = box_h / (hi - lo)[1]
    w, h = scale * (hi - lo)

    def draw(svg, cx, cy, k, op):
        svg.rect(cx - w / 2 - pad, cy - h / 2 - pad, w + 2 * pad, h + 2 * pad, fill="white", col="#C8C8C8", sw=0.7, rx=2)
        draw_skeleton(svg, frames[k], cx - scale * (lo[0] + hi[0]) / 2, cy - scale * (lo[1] + hi[1]) / 2, scale,
                      op=op, w=0.9)
    return draw, h + 2 * pad


def trapezoid(svg, x0, x1, cy, h_wide, h_narrow, wide_left, formula):
    hl, hr = (h_wide, h_narrow) if wide_left else (h_narrow, h_wide)
    svg.path(f"M{x0},{cy - hl / 2} L{x1},{cy - hr / 2} L{x1},{cy + hr / 2} L{x0},{cy + hl / 2} Z",
             fill="#F3F3F3", col="#555555", w=0.9)
    svg.text((x0 + x1) / 2, cy + 3.5, formula, 10.5)



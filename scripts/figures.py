# ================================================================== figures 2 and 3: the trained MTGP-VAE
def sign_posteriors(ckpt):
    """The model, and every sign's statistics and q(mu_s) from its training clips (shared by figures 2 and 3)."""
    model, _ = load_model(ckpt)
    vae, prior = model.vae, model.prior
    m0 = np.asarray(prior.m())
    l0, ls, k_clip = (np.asarray(a) for a in chols(prior))
    tr = load("training")
    n_signs = len(sign_names())
    y_tr, lam_tr = grid_codes(m0, *encode(vae, tr["x"]), tr["idx"])
    stats = sign_stats(ls, y_tr, lam_tr, tr["signs"], n_signs)
    ms, cs = (np.asarray(a) for a in sign_means(jnp.asarray(l0), jnp.asarray(stats[0]), jnp.asarray(stats[1])))
    lengths = np.array([int(np.median(tr["lengths"][tr["signs"] == s])) for s in range(n_signs)])
    return {"model": model, "m0": m0, "k_clip": k_clip, "stats": stats, "ms": ms, "cs": cs, "lengths": lengths}


# ================================================================== figure 2: outlier detection and correction
def loo(m, c, y, s2, gi, f, rng):
    """One clip, every dim. m (d, G), c (d, G, G): prior of z - m0; y, s2 (n, d) at grid points gi (n,).
    Returns the LOO log-likelihood of every frame (n,) and one sample of z - m0 at frame f given the others (d,)."""
    ll, z = np.zeros(len(gi)), np.zeros(len(m))
    keep = np.arange(len(gi)) != f
    for k in range(len(m)):
        kk = c[k][np.ix_(gi, gi)] + np.diag(s2[:, k])
        r = y[:, k] - m[k, gi]
        kinv = np.linalg.inv(kk)
        var = 1 / np.diag(kinv)
        mean_err = (kinv @ r) * var  # y_j - LOO predictive mean
        ll += -0.5 * (np.log(2 * np.pi * var) + mean_err ** 2 / var)
        o = gi[keep]
        ko = c[k][np.ix_(o, o)] + np.diag(s2[keep, k])
        kfo = c[k][gi[f], o]
        mu = m[k, gi[f]] + kfo @ np.linalg.solve(ko, r[keep])
        v = c[k][gi[f], gi[f]] - kfo @ np.linalg.solve(ko, kfo)
        z[k] = mu + np.sqrt(max(v, 0)) * rng.standard_normal()
    return ll, z



class Svg:
    def __init__(self, w, h):
        self.w, self.h, self.items = w, h, []

    def add(self, s):
        self.items.append(s)

    def line(self, x0, y0, x1, y1, col=INK, w=1.0, dash=None, op=1.0, cap="round"):
        d = f' stroke-dasharray="{dash}"' if dash else ""
        self.add(f'<line x1="{x0:.2f}" y1="{y0:.2f}" x2="{x1:.2f}" y2="{y1:.2f}" stroke="{col}" '
                 f'stroke-width="{w}" stroke-opacity="{op}" stroke-linecap="{cap}"{d}/>')

    def path(self, d, fill="none", col="none", w=1.0, op=1.0, fop=1.0, dash=None, join="round"):
        ds = f' stroke-dasharray="{dash}"' if dash else ""
        self.add(f'<path d="{d}" fill="{fill}" fill-opacity="{fop}" stroke="{col}" stroke-width="{w}" '
                 f'stroke-opacity="{op}" stroke-linejoin="{join}"{ds}/>')

    def rect(self, x, y, w, h, fill="none", col="none", sw=1.0, rx=0):
        self.add(f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" rx="{rx}" fill="{fill}" '
                 f'stroke="{col}" stroke-width="{sw}"/>')

    def circle(self, x, y, r, fill=INK, col="none", sw=0.6, op=1.0):
        self.add(f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{r}" fill="{fill}" fill-opacity="{op}" stroke="{col}" '
                 f'stroke-width="{sw}"/>')

    def text(self, x, y, s, size=11, anchor="middle", col=INK, style=""):
        """s may contain <tspan> markup (see m())."""
        self.add(f'<text xml:space="preserve" x="{x:.2f}" y="{y:.2f}" font-size="{size}" text-anchor="{anchor}" fill="{col}" '
                 f'font-family="{FONT}" {style}>{s}</text>')

    def arrow(self, x0, y0, x1, y1, col=INK, w=1.0, head=5):
        self.line(x0, y0, x1, y1, col, w)
        a = np.arctan2(y1 - y0, x1 - x0)
        p = [(x1, y1), (x1 - head * np.cos(a - 0.4), y1 - head * np.sin(a - 0.4)),
             (x1 - head * np.cos(a + 0.4), y1 - head * np.sin(a + 0.4))]
        self.path("M" + " L".join(f"{u:.2f},{v:.2f}" for u, v in p) + " Z", fill=col)

    def save(self, path):
        with open(path, "w") as f:
            f.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {self.w} {self.h}" '
                    f'width="{self.w}" height="{self.h}">\n<rect width="100%" height="100%" fill="white"/>\n')
            f.write("\n".join(self.items))
            f.write("\n</svg>\n")


def it(s):
    return f'<tspan font-style="italic">{s}</tspan>'


def sub(s, after="", size=8):
    """Subscript s, then `after` back on the baseline."""
    after = after.replace(" ", "&#160;")  # renderers drop plain spaces at tspan edges
    return f'<tspan dy="3" font-size="{size}">{s}</tspan><tspan dy="-3">{after or "&#8203;"}</tspan>'


def draw_skeleton(svg, frame, x0, y0, scale, op=1.0, w=1.1):
    pts = frame.reshape(-1, 2)
    for p, s in SLICES.items():
        col = COL[SKEL_PART[p]]
        lw = w * (0.6 if SKEL_PART[p] == "face" else 1.0)
        for a, b in EDGES[p]:
            (u0, v0), (u1, v1) = pts[s][a], pts[s][b]
            svg.line(x0 + scale * u0, y0 + scale * v0, x0 + scale * u1, y0 + scale * v1, col, lw, op=op)


